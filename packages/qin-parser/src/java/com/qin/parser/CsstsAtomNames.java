    public static PseudoVariant pseudoVariant(String name) {
        int separator = name.indexOf("$$");
        if (separator <= 0) return null;
        String base = name.substring(0, separator);
        return new PseudoVariant(base, List.of(name.substring(separator + 2).split("\\$\\$", -1)));
    }

    public record PseudoVariant(String base, List<String> pseudos) { }

    public static AtomData parseTsAtom(String name) {
        for (String propertyName : PROPERTY_NAMES) {
            String property = PROPERTIES.get(propertyName);
            if (!name.startsWith(propertyName) || name.length() == propertyName.length()) continue;
            String valuePart = name.substring(propertyName.length());
            if (!(Character.isUpperCase(valuePart.charAt(0)) || Character.isDigit(valuePart.charAt(0))
                    || (valuePart.length() > 1 && valuePart.charAt(0) == 'N' && Character.isDigit(valuePart.charAt(1))))) continue;
            String value = tsValueToCss(valuePart);
            boolean colorProperty = property.contains("color") || "fill".equals(property) || "stroke".equals(property);
            if (value.matches("^[+-]?\\d.*") || KEYWORD_VALUES.contains(value)
                    || (colorProperty && NAMED_COLORS.contains(value)) || value.contains("-")
                    || value.contains("%") || value.contains("/")) return new AtomData(property, value);
        }
        return null;
    }

