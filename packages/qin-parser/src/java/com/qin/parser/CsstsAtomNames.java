    private static String tsValueToCss(String value) {
        String result = value;
        if (result.length() > 1 && result.charAt(0) == 'N' && Character.isDigit(result.charAt(1))) result = "-" + result.substring(1);
        result = result.replace("pct", "%").replaceAll("(\\d)p(\\d)", "$1.$2").replaceAll("(\\d)s(\\d)", "$1/$2");
        result = result.replaceAll("([a-z])([A-Z])", "$1-$2").replaceAll("([a-zA-Z])(\\d)", "$1-$2");
        return result.toLowerCase(java.util.Locale.ROOT);
    }
